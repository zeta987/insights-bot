// RichMessageByteLimit caps the Markdown source of one rich message in UTF-8
// bytes. Telegram keeps about 32768 bytes of text and link URLs per rich
// message and silently drops whatever follows, so the source stays below that
// with headroom. Counting UTF-16 units let CJK recaps overshoot almost
// threefold and lose their tail.
const RichMessageByteLimit = 30000

// textBudget measures text against a delivery limit in one unit of length.
type textBudget struct {
	size        func(text string) int
	runesWithin func(runes []rune, limit int) int
}

var (
	// utf16UnitBudget matches how Telegram measures ordinary messages.
	utf16UnitBudget = textBudget{
		size:        tgbot.MessageLengthInUTF16Units,
		runesWithin: tgbot.RuneCountWithinUTF16Units,
	}
	// utf8ByteBudget matches how Telegram measures rich messages.
	utf8ByteBudget = textBudget{
		size:        func(text string) int { return len(text) },
		runesWithin: runeCountWithinUTF8Bytes,
	}
)

// runeCountWithinUTF8Bytes reports how many leading runes fit within maxBytes
// once encoded as UTF-8. A rune that would exceed the budget is left out.
func runeCountWithinUTF8Bytes(runes []rune, maxBytes int) int {
	size := 0

	for index, r := range runes {
		runeSize := utf8.RuneLen(r)
		if runeSize < 0 {
			// Invalid runes are encoded as the replacement character.
			runeSize = utf8.RuneLen(utf8.RuneError)
		}

		size += runeSize
		if size > maxBytes {
			return index
		}
	}

	return len(runes)
}

const (
	richRecapDetailsOpen   = "<details><summary>詳細總結</summary>\n\n"
	richRecapDetailsClose  = "\n\n</details>"
	maxReferencesPerMarker = 5
)

var richRecapReferencePattern = regexp.MustCompile(`\{\{tg-ref:([^{}\r\n]*)\}\}`)
var richMarkdownHTMLTagPattern = regexp.MustCompile(`(?i)</?[a-z][^>\r\n]*>`)
var richMarkdownInlineLinkPattern = regexp.MustCompile(`!?\[([^\]\r\n]+)\]\([^)\r\n]+\)`)
var richMarkdownBareURLPattern = regexp.MustCompile(`https?://[^\s<>()]+`)
var richMarkdownLinkSpanPattern = regexp.MustCompile(`!?\[[^\]\r\n]*\]\([^)\s]+\)`)

// Telegram parses "@word" as a live mention entity only when the "@" sits at
// the start of the text or after a non-word character, so email-like tokens
// (word character before "@") stay untouched. "@+" collapses stacked "@@name"
// so stripping can never leave a fresh mention behind.
var richMarkdownMentionPattern = regexp.MustCompile(`(^|[^0-9A-Za-z_])@+([0-9A-Za-z_])`)

// richMarkdownInlineSpanPatterns capture the visible text of inline Rich
// Markdown decorations in group 1 so the text survives when a decoration is
// stripped.
var richMarkdownInlineSpanPatterns = []*regexp.Regexp{
	regexp.MustCompile(`\*\*((?:\\.|[^*\r\n])*)\*\*`),
	regexp.MustCompile(`__((?:\\.|[^_\r\n])*)__`),
	regexp.MustCompile(`~~((?:\\.|[^~\r\n])*)~~`),
	regexp.MustCompile("`([^`\\r\\n]*)`"),
	regexp.MustCompile(`\*((?:\\.|[^*\r\n])*)\*`),
	regexp.MustCompile(`_((?:\\.|[^_\r\n])*)_`),
}

var richMarkdownProtectedSpanPatterns = append(
	[]*regexp.Regexp{richMarkdownLinkSpanPattern},
	richMarkdownInlineSpanPatterns...,
)

// richMarkdownEscapableCharacters is the single set of characters escaped by
// EscapeRichMarkdownText and reversed by UnescapeRichMarkdownText.
const richMarkdownEscapableCharacters = "\\*_{}[]()#+-.!|><~`"

var richMarkdownTextEscaper = newRichMarkdownTextEscaper()

func newRichMarkdownTextEscaper() *strings.Replacer {
	pairs := make([]string, 0, len(richMarkdownEscapableCharacters)*2)
	for _, character := range richMarkdownEscapableCharacters {
		pairs = append(pairs, string(character), `\`+string(character))
	}

	return strings.NewReplacer(pairs...)
}

// EscapeRichMarkdownText escapes untrusted plain text for insertion into Rich
// Markdown generated by the application.
func EscapeRichMarkdownText(text string) string {
	text = strings.ReplaceAll(text, "\r\n", " ")
	text = strings.ReplaceAll(text, "\r", " ")
	text = strings.ReplaceAll(text, "\n", " ")
	return richMarkdownTextEscaper.Replace(strings.TrimSpace(text))
}

// UnescapeRichMarkdownText removes the escapes added by EscapeRichMarkdownText
// so the text can be rendered on plain-text surfaces.
func UnescapeRichMarkdownText(text string) string {
	runes := []rune(text)

	var builder strings.Builder

	builder.Grow(len(text))

	for index := 0; index < len(runes); index++ {
		if runes[index] == '\\' && index+1 < len(runes) &&
			strings.ContainsRune(richMarkdownEscapableCharacters, runes[index+1]) {
			index++
		}

		builder.WriteRune(runes[index])
	}

	return builder.String()
}

func formatChatID(chatID int64) string {
	chatIDStr := strconv.FormatInt(chatID, 10)
	if strings.HasPrefix(chatIDStr, "-100") {
		return strings.TrimPrefix(chatIDStr, "-100")
	}

	return chatIDStr
}

// SanitizeDetailedRecapMarkdown keeps the supported recap structure while
// removing model-authored HTML and links. Controlled source markers are
// resolved into whitelisted Telegram links after this function returns.
func SanitizeDetailedRecapMarkdown(markdown string) string {
	return sanitizeRichRecapMarkdown(markdown, func(line string) string {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, ">") {
			line = strings.TrimSpace(strings.TrimLeft(trimmed, ">"))
		}

		if strings.HasPrefix(strings.TrimSpace(line), "* ") {
			indentLength := len(line) - len(strings.TrimLeft(line, " \t"))
			line = line[:indentLength] + "- " + strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "* "))
		}

		if strings.Contains(line, "|") {
			line = strings.ReplaceAll(line, "|", "\\|")
		}

		return line
	})
}

// SanitizeCondensedRecapMarkdown preserves the richer visual vocabulary used
// by condensed recaps while removing model-authored HTML and links.
func SanitizeCondensedRecapMarkdown(markdown string) string {
	return sanitizeRichRecapMarkdown(markdown, func(line string) string {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "* ") {
			line = "- " + strings.TrimSpace(strings.TrimPrefix(trimmed, "* "))
			trimmed = strings.TrimSpace(line)
		}

		if strings.HasPrefix(trimmed, "# ") || strings.HasPrefix(trimmed, "## ") {
			line = "### " + strings.TrimSpace(strings.TrimLeft(trimmed, "#"))
		}

		return line
	})
}

// sanitizeRichRecapMarkdown strips model-authored HTML, links, and code fences
// shared by every recap flavor, then lets transformLine rewrite what remains.
func sanitizeRichRecapMarkdown(markdown string, transformLine func(line string) string) string {
	markdown = normalizeRichMarkdown(markdown)
	markdown = richMarkdownInlineLinkPattern.ReplaceAllString(markdown, "$1")
	markdown = richMarkdownHTMLTagPattern.ReplaceAllString(markdown, "")
	markdown = richMarkdownBareURLPattern.ReplaceAllString(markdown, "")
	markdown = neutralizeRichMarkdownMentions(markdown)

	lines := strings.Split(markdown, "\n")
	sanitizedLines := make([]string, 0, len(lines))

	for _, line := range lines {
		if richMarkdownFenceMarker(strings.TrimSpace(line)) != "" {
			continue
		}

		sanitizedLines = append(sanitizedLines, strings.TrimRight(transformLine(line), " \t"))
	}

	return normalizeRichMarkdown(strings.Join(sanitizedLines, "\n"))
}

// ResolveRichRecapReferences replaces controlled virtual-message markers with
// links to real Telegram messages. Markers are removed for chat types that do
// not support private supergroup links.
func ResolveRichRecapReferences(
	markdown string,
	chatID int64,
	chatType telegram.ChatType,
	virtualToReal map[int64]int64,
) string {
	return richRecapReferencePattern.ReplaceAllStringFunc(markdown, func(marker string) string {
		if chatType != telegram.ChatTypeSuperGroup {
			return ""
		}

		matches := richRecapReferencePattern.FindStringSubmatch(marker)
		if len(matches) != 2 {
			return ""
		}

		links := make([]string, 0, maxReferencesPerMarker)
		seenRealIDs := make(map[int64]struct{}, maxReferencesPerMarker)
		for _, rawID := range strings.Split(matches[1], ",") {
			virtualID, err := strconv.ParseInt(strings.TrimSpace(rawID), 10, 64)
			if err != nil || virtualID <= 0 {
				continue
			}

			realID, exists := virtualToReal[virtualID]
			if !exists || realID <= 0 {
				continue
			}
			if _, duplicated := seenRealIDs[realID]; duplicated {
				continue
			}

			seenRealIDs[realID] = struct{}{}
			links = append(links, fmt.Sprintf(
				"[%d](https://t.me/c/%s/%d)",
				len(links)+1,
				formatChatID(chatID),
				realID,
			))
			if len(links) == maxReferencesPerMarker {
				break
			}
		}

		return strings.Join(links, " ")
	})
}

// ComposeRichRecapMessages places the condensed summary before collapsible
// detailed Rich Markdown and splits oversized output into valid containers.
func ComposeRichRecapMessages(condensedSummary string, detailedSummaries []string) []string {
	condensedSummary = normalizeRichMarkdown(condensedSummary)
	detailedSummary := joinRichMarkdownSummaries(detailedSummaries)

	if condensedSummary == "" && detailedSummary == "" {
		return []string{}
	}
	if detailedSummary == "" {
		return packRichMarkdownBlocks(
			splitRichMarkdownBlocks(condensedSummary),
			RichMessageByteLimit,
			RichMessageByteLimit,
		)
	}

	wrapperSize := utf8ByteBudget.size(richRecapDetailsOpen + richRecapDetailsClose)
	detailBodyLimit := RichMessageByteLimit - wrapperSize
	condensedPrefix := ""
	if condensedSummary != "" {
		condensedPrefix = condensedSummary + "\n\n"
	}
	firstDetailBodyLimit := detailBodyLimit - utf8ByteBudget.size(condensedPrefix)

	messages := make([]string, 0, 1)
	if firstDetailBodyLimit <= 0 {
		messages = append(messages, packRichMarkdownBlocks(
			splitRichMarkdownBlocks(condensedSummary),
			RichMessageByteLimit,
			RichMessageByteLimit,
		)...)
		condensedPrefix = ""
		firstDetailBodyLimit = detailBodyLimit
	}

	detailChunks := packRichMarkdownBlocks(
		splitRichMarkdownBlocks(detailedSummary),
		firstDetailBodyLimit,
		detailBodyLimit,
	)
	for index, detailChunk := range detailChunks {
		prefix := ""
		if index == 0 {
			prefix = condensedPrefix
		}

		messages = append(messages, prefix+richRecapDetailsOpen+detailChunk+richRecapDetailsClose)
	}

	return messages
}

// neutralizeRichMarkdownMentions drops the "@" prefix from model-emitted
// @username tokens so recap deliveries never notify the mentioned users.
func neutralizeRichMarkdownMentions(markdown string) string {
	return richMarkdownMentionPattern.ReplaceAllString(markdown, "${1}${2}")
}

func normalizeRichMarkdown(markdown string) string {
	markdown = strings.ReplaceAll(markdown, "\r\n", "\n")
	markdown = strings.ReplaceAll(markdown, "\r", "\n")
	return strings.TrimSpace(markdown)
}

func joinRichMarkdownSummaries(summaries []string) string {
	nonEmpty := make([]string, 0, len(summaries))
	for _, summary := range summaries {
		if normalized := normalizeRichMarkdown(summary); normalized != "" {
			nonEmpty = append(nonEmpty, normalized)
		}
	}

	return strings.Join(nonEmpty, "\n\n")
}

func splitRichMarkdownBlocks(markdown string) []string {
	markdown = normalizeRichMarkdown(markdown)
	if markdown == "" {
		return []string{}
	}

	lines := strings.Split(markdown, "\n")
	blocks := make([]string, 0)
	currentLines := make([]string, 0)
	inFence := false
	fenceMarker := ""

	flush := func() {
		block := strings.TrimSpace(strings.Join(currentLines, "\n"))
		if block != "" {
			blocks = append(blocks, block)
		}
		currentLines = currentLines[:0]
	}

	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if marker := richMarkdownFenceMarker(trimmed); marker != "" {
			if !inFence {
				inFence = true
				fenceMarker = marker
			} else if strings.HasPrefix(trimmed, fenceMarker) {
				inFence = false
				fenceMarker = ""
			}
			currentLines = append(currentLines, line)
			continue
		}

		if trimmed == "" && !inFence {
			flush()
			continue
		}
		currentLines = append(currentLines, line)
	}
	flush()

	return mergeStandaloneHeadings(blocks)
}

func richMarkdownFenceMarker(line string) string {
	if strings.HasPrefix(line, "```") {
		return "```"
	}
	if strings.HasPrefix(line, "~~~") {
		return "~~~"
	}
	return ""
}

func mergeStandaloneHeadings(blocks []string) []string {
	merged := make([]string, 0, len(blocks))
	for index := 0; index < len(blocks); index++ {
		if isStandaloneMarkdownHeading(blocks[index]) && index+1 < len(blocks) {
			merged = append(merged, blocks[index]+"\n\n"+blocks[index+1])
			index++
			continue
		}
		merged = append(merged, blocks[index])
	}
	return merged
}

func isStandaloneMarkdownHeading(block string) bool {
	if strings.Contains(block, "\n") {
		return false
	}
	trimmed := strings.TrimSpace(block)
	for level := 1; level <= 6; level++ {
		if strings.HasPrefix(trimmed, strings.Repeat("#", level)+" ") {
			return true
		}
	}
	return false
}

func packRichMarkdownBlocks(blocks []string, firstLimit, laterLimit int) []string {
	if len(blocks) == 0 || firstLimit <= 0 || laterLimit <= 0 {
		return []string{}
	}

	chunks := make([]string, 0, 1)
	current := ""
	currentCount := 0
	currentLimit := firstLimit

	for _, originalBlock := range blocks {
		remainingBlock := originalBlock
		remainingCount := utf8ByteBudget.size(remainingBlock)

		for remainingBlock != "" {
			separator := ""
			separatorCount := 0

			if current != "" {
				separator = "\n\n"
				separatorCount = len(separator)
			}

			if currentCount+separatorCount+remainingCount <= currentLimit {
				current += separator + remainingBlock
				currentCount += separatorCount + remainingCount
				remainingBlock = ""

				continue
			}

			if current != "" {
				chunks = append(chunks, current)
				current = ""
				currentCount = 0
				currentLimit = laterLimit

				continue
			}

			head, tail := splitFragmentAtPreferredCut(remainingBlock, currentLimit, utf8ByteBudget, richMarkdownProtectedSpanPatterns)
			if head == "" {
				return chunks
			}

			chunks = append(chunks, head)
			currentLimit = laterLimit
			remainingBlock = tail
			remainingCount = utf8ByteBudget.size(remainingBlock)
		}
	}

	if current != "" {
		chunks = append(chunks, current)
	}
	return chunks
}

// splitFragmentAtPreferredCut cuts fragment into a head that fits limit, as
// measured by budget, and the remaining tail. It prefers sentence boundaries
// and avoids cuts inside spans matched by protectedPatterns.
func splitFragmentAtPreferredCut(fragment string, limit int, budget textBudget, protectedPatterns []*regexp.Regexp) (string, string) {
	runes := []rune(fragment)
	runeLimit := budget.runesWithin(runes, limit)
	if runeLimit >= len(runes) {
		return fragment, ""
	}
	if runeLimit < 1 {
		// Never stall on a single rune wider than the remaining budget.
		runeLimit = 1
	}

	cut := preferredFragmentCut(runes, runeLimit)
	cut = adjustCutForProtectedSpans(fragment, runes, cut, runeLimit, protectedPatterns)

	head := strings.TrimSpace(string(runes[:cut]))
	tail := strings.TrimSpace(string(runes[cut:]))
	if head == "" {
		head = string(runes[:runeLimit])
		tail = strings.TrimSpace(string(runes[runeLimit:]))
	}
	return head, tail
}

func preferredFragmentCut(runes []rune, limit int) int {
	cut := limit
	for index := limit - 1; index >= limit/2; index-- {
		switch runes[index] {
		case '\n', ' ', '\t', '。', '！', '？', '；':
			cut = index + 1
			index = -1
		}
	}

	return cut
}

func adjustCutForProtectedSpans(fragment string, runes []rune, cut, limit int, protectedPatterns []*regexp.Regexp) int {
	// Only spans overlapping the cut can move it, so bound the scan instead of
	// rescanning the whole fragment on every chunk. Spans longer than the
	// window cannot fit inside one chunk and are hard-cut regardless.
	if len(runes) > 2*limit {
		fragment = string(runes[:2*limit])
	}

	protectedStart := cut
	protectedEnd := 0

	for _, pattern := range protectedPatterns {
		for _, match := range pattern.FindAllStringIndex(fragment, -1) {
			start := utf8.RuneCountInString(fragment[:match[0]])
			end := start + utf8.RuneCountInString(fragment[match[0]:match[1]])

			if start >= cut || cut >= end {
				continue
			}
			if start > 0 && start < protectedStart {
				protectedStart = start
			}
			if start == 0 && end <= limit && end > protectedEnd {
				protectedEnd = end
			}
		}
	}

	adjusted := protectedStart
	if adjusted == cut && protectedEnd != 0 {
		adjusted = protectedEnd
	}
	if adjusted > 0 && adjusted < len(runes) && runes[adjusted-1] == '\\' {
		adjusted--
	}
	if adjusted <= 0 || adjusted > limit {
		return cut
	}
	return adjusted
}
